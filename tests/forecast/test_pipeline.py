import pytest
from delphi.forecast import (
    ForecastConfig, ForecastOrchestrator, ForecastRequest, 
    ScenarioBuilder, ProbabilityCalibrator, ForecastValidator,
    EvidenceRegistry, EvidenceItem
)

def test_pipeline_orchestration():
    config = ForecastConfig()
    orchestrator = ForecastOrchestrator(config)
    
    req = ForecastRequest(
        article_text="Test",
        publication_timestamp="2026-08-30T00:00Z",
        prediction_information_cutoff="2026-09-01T00:00Z",
        domain="geopolitics",
        requested_forecast_horizon="30 days"
    )
    
    report = orchestrator.generate_forecast(req)
    
    # 2 scenarios generated by mock
    assert len(report.candidate_scenarios) == 2
    assert report.temporal_safety_status == "VALID"
    assert "UNCALIBRATED / RESEARCH MODE" in report.forecast_status
    
    # Check probabilities sum to 1
    total_prob = sum(report.scenario_probabilities.values())
    assert abs(total_prob - 1.0) < 1e-4

def test_scenario_builder_deduplication():
    config = ForecastConfig(max_scenarios=3)
    builder = ScenarioBuilder(config)
    
    # Provide identical trajectories
    trajectories = [
        {"trajectory": [{"event_type": 1, "time_bin": 1, "actor": 1, "target": 1, "domain": 1}], "sequence_score": -1.0},
        {"trajectory": [{"event_type": 1, "time_bin": 1, "actor": 1, "target": 1, "domain": 1}], "sequence_score": -0.5} # Better score
    ]
    
    scenarios = builder.build_scenarios(trajectories)
    
    assert len(scenarios) == 1
    assert scenarios[0].sequence_score == -0.5

def test_probability_normalization():
    config = ForecastConfig()
    calibrator = ProbabilityCalibrator(config)
    
    from delphi.forecast.schemas import ScenarioCandidate
    s1 = ScenarioCandidate(scenario_id="S1", title="", trajectory=[], supporting_evidence=[], contradictory_evidence=[], raw_scenario_score=-1.0)
    s2 = ScenarioCandidate(scenario_id="S2", title="", trajectory=[], supporting_evidence=[], contradictory_evidence=[], raw_scenario_score=-2.0)
    
    probs, status = calibrator.calibrate([s1, s2])
    
    assert "UNCALIBRATED" in status
    assert abs(sum(probs.values()) - 1.0) < 1e-4
    assert probs["S1"] > probs["S2"]

def test_forecast_validator_leakage():
    report_stub = type('obj', (object,), {
        'scenario_probabilities': {"S1": 1.0},
        'candidate_scenarios': [type('obj', (object,), {'scenario_id': "S1"})],
        'provenance': type('obj', (object,), {
            'prediction_cutoff': "2026-01-01T00:00Z",
            'checkpoint_training_end_time': "2026-02-01T00:00Z" # LEAK!
        }),
        'supporting_evidence': [],
        'contradictory_evidence': [],
        'indicators_to_watch': []
    })
    
    with pytest.raises(ValueError, match="Temporal Leakage: checkpoint"):
        ForecastValidator.validate(report_stub)
